import { startUncover, answerUncover, finishUncover } from '../controllers/uncoverController.js';
import { startStreakChain, answerStreakChain, finishStreakChain } from '../controllers/streakChainController.js';
import { hideQuestionSolutions } from '../utils/questionValidation.js';
import { optionalQuizAuth, startQuizAttempt, checkQuizAnswer, finishQuizAttempt } from '../controllers/quizAttemptController.js';
import express from 'express';
import { getQuestions, getQuestionFilters, getQuestionById, getUnsolvedQuestions, getRandom50, markSolved, dailyLinux, getDailyChallengeStatus, completeDailyChallenge, resetBasicStats, dailyNetwork, resetLinuxStats, resetArduinoStats, resetNetworkStats, resetAcadnetStats, getLinuxOverviewTest, submitRandom50, exportAllQuestions, exportFilteredQuestions, searchQuestions, deleteQuestion, updateQuestion } from '../controllers/questionController.js';
import { authMiddleware } from '../middleware/authMiddleware.js';
import { checkRole } from '../middleware/checkRole.js';

const router = express.Router();
router.post('/uncover/start', authMiddleware, startUncover);
router.post('/uncover/answer', authMiddleware, answerUncover);
router.post('/uncover/finish', authMiddleware, finishUncover);
router.post('/chain/start', authMiddleware, startStreakChain);
router.post('/chain/answer', authMiddleware, answerStreakChain);
router.post('/chain/finish', authMiddleware, finishStreakChain);
router.post('/attempts/start', optionalQuizAuth, startQuizAttempt);
router.post('/attempts/check', optionalQuizAuth, checkQuizAnswer);
router.post('/attempts/finish', optionalQuizAuth, finishQuizAttempt());

router.get('/unsolved', hideQuestionSolutions, authMiddleware, getUnsolvedQuestions);
router.get('/random50', hideQuestionSolutions, getRandom50);
router.get('/dailyLinux', hideQuestionSolutions, dailyLinux);
router.get('/dailyNetwork', hideQuestionSolutions, dailyNetwork);
router.get('/dailyChallengeStatus', authMiddleware, getDailyChallengeStatus);
router.get('/linux-overview-test', hideQuestionSolutions, getLinuxOverviewTest);
router.post('/markSolved', authMiddleware, markSolved);
router.post('/examPoints', authMiddleware, markSolved);
router.post('/completeDailyChallenge', authMiddleware, completeDailyChallenge);
router.post('/resetBasicStats', authMiddleware, resetBasicStats);
router.post('/resetLinuxStats', authMiddleware, resetLinuxStats);
router.post('/resetArduinoStats', authMiddleware, resetArduinoStats);
router.post('/resetNetworkStats', authMiddleware, resetNetworkStats);
router.post('/resetAcadnetStats', authMiddleware, resetAcadnetStats);
router.get('/export', authMiddleware, checkRole('root'), exportAllQuestions);
router.get('/search/export', authMiddleware, checkRole('root'), exportFilteredQuestions);
router.get('/search/filters', authMiddleware, checkRole('root'), getQuestionFilters);
router.get('/search', authMiddleware, checkRole('root'), searchQuestions);
router.delete('/:id', authMiddleware, checkRole('root'), deleteQuestion);
router.put('/:id', authMiddleware, checkRole('root'), updateQuestion);
router.get('/', hideQuestionSolutions, getQuestions);
router.get('/:id', hideQuestionSolutions, getQuestionById);
router.post('/submitRandom50', authMiddleware, submitRandom50);

export default router;
